-----------------------------------------------------------------------
-- CLIENTE
-----------------------------------------------------------------------
CREATE TABLE CLIENTE (
    ID            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME          VARCHAR(150)  NOT NULL,
    CPF_CNPJ      VARCHAR(18)   NOT NULL,
    EMAIL         VARCHAR(150),
    TELEFONE      VARCHAR(20),
    ENDERECO      VARCHAR(250),
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO         BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE UNIQUE INDEX UK_CLIENTE_CPF_CNPJ ON CLIENTE (CPF_CNPJ);
CREATE INDEX IDX_CLIENTE_NOME ON CLIENTE (NOME);

-----------------------------------------------------------------------
-- PRODUTO
-----------------------------------------------------------------------
CREATE TABLE PRODUTO (
    ID            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DESCRICAO     VARCHAR(150)   NOT NULL,
    SKU           VARCHAR(30),
    PRECO         DECIMAL(15,2)  NOT NULL,
    ESTOQUE_ATUAL INTEGER DEFAULT 0 NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO         BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO >= 0),
    CONSTRAINT CK_PRODUTO_ESTOQUE CHECK (ESTOQUE_ATUAL >= 0)
);

CREATE INDEX IDX_PRODUTO_DESCRICAO ON PRODUTO (DESCRICAO);
CREATE INDEX IDX_PRODUTO_SKU ON PRODUTO (SKU);

-----------------------------------------------------------------------
-- VENDA
-----------------------------------------------------------------------
CREATE TABLE VENDA (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLIENTE_ID          INTEGER NOT NULL,
    DATA_VENDA          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VALOR_TOTAL         DECIMAL(15,2) NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'PENDENTE' NOT NULL,
    DATA_QUITACAO       TIMESTAMP,
    DATA_CANCELAMENTO   TIMESTAMP,
    MOTIVO_CANCELAMENTO VARCHAR(250),
    RELATORIO_ENVIADO   BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT FK_VENDA_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE(ID),
    CONSTRAINT CK_VENDA_STATUS CHECK (STATUS IN ('PENDENTE', 'QUITADA', 'CANCELADA')),
    CONSTRAINT CK_VENDA_VALOR CHECK (VALOR_TOTAL >= 0)
);

CREATE INDEX IDX_VENDA_CLIENTE ON VENDA (CLIENTE_ID);
CREATE INDEX IDX_VENDA_STATUS ON VENDA (STATUS);
CREATE INDEX IDX_VENDA_DATA ON VENDA (DATA_VENDA);

-----------------------------------------------------------------------
-- VENDA_ITEM
-- PRECO_UNITARIO eh um snapshot do preco no momento da venda.
-----------------------------------------------------------------------
CREATE TABLE VENDA_ITEM (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VENDA_ID        INTEGER NOT NULL,
    PRODUTO_ID      INTEGER NOT NULL,
    QUANTIDADE      INTEGER NOT NULL,
    PRECO_UNITARIO  DECIMAL(15,2) NOT NULL,
    VALOR_TOTAL     DECIMAL(15,2) NOT NULL,
    CONSTRAINT FK_VENDA_ITEM_VENDA FOREIGN KEY (VENDA_ID) REFERENCES VENDA(ID) ON DELETE CASCADE,
    CONSTRAINT FK_VENDA_ITEM_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTO(ID),
    CONSTRAINT CK_VENDA_ITEM_QUANTIDADE CHECK (QUANTIDADE > 0),
    CONSTRAINT CK_VENDA_ITEM_PRECO CHECK (PRECO_UNITARIO > 0),
    CONSTRAINT CK_VENDA_ITEM_VALOR_TOTAL CHECK (VALOR_TOTAL >= 0)
);

CREATE INDEX IDX_VENDA_ITEM_VENDA ON VENDA_ITEM (VENDA_ID);
CREATE INDEX IDX_VENDA_ITEM_PRODUTO ON VENDA_ITEM (PRODUTO_ID);

-----------------------------------------------------------------------
-- INTEGRACAO_OUTBOX
-- Eventos gravados na mesma transacao da operacao de negocio e
-- processados de forma assincrona (envio ao ERP Financeiro / e-mail),
-- com nova tentativa em caso de falha.
-----------------------------------------------------------------------
CREATE TABLE INTEGRACAO_OUTBOX (
    ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TIPO                VARCHAR(40) NOT NULL,
    VENDA_ID            INTEGER NOT NULL,
    STATUS              VARCHAR(20) DEFAULT 'PENDENTE' NOT NULL,
    TENTATIVAS          INTEGER DEFAULT 0 NOT NULL,
    PROXIMA_TENTATIVA   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ULTIMO_ERRO         VARCHAR(1000),
    DATA_CRIACAO        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DATA_PROCESSAMENTO  TIMESTAMP,
    CONSTRAINT FK_OUTBOX_VENDA FOREIGN KEY (VENDA_ID) REFERENCES VENDA(ID),
    CONSTRAINT CK_OUTBOX_TIPO CHECK (TIPO IN ('ENVIAR_VENDA', 'CANCELAR_VENDA', 'ENVIAR_EMAIL_CONFIRMACAO')),
    CONSTRAINT CK_OUTBOX_STATUS CHECK (STATUS IN ('PENDENTE', 'PROCESSADO', 'FALHA'))
);

CREATE INDEX IDX_OUTBOX_PENDENTES ON INTEGRACAO_OUTBOX (STATUS, PROXIMA_TENTATIVA);

COMMIT;

